import type {
  CuePosition,
  InsertionMode,
  InterstitialState,
  NavigationRestriction,
  ResolutionState,
  SlotState,
  TimelineOccupancy,
  TimelineStyle,
} from './enums';
import type { AdIdentifier, MediaReference, SkipControl, TrackingEvent, Verification } from './records';

/**
 * Whether departure from and return to primary content align to segment boundaries. Honored only when the primary
 * element exposes segment boundaries, and only on live streams.
 *
 * @internal
 */
export interface InterstitialSnap {
  out: boolean;
  in: boolean;
}

/**
 * A region on the primary timeline during which something other than primary content is presented: an ad pod, a bumper,
 * a recap, a slate. Carries the SVTA2053 `Pod` fields plus the HLS Interstitials navigation and UI fields plus runtime
 * state. The session owns `state`, `played`, `currentSlot` and `currentTime`; adapters own `resolution` through the
 * host.
 *
 * @internal
 */
export interface Interstitial {
  /**
   * Unique within the session. For manifest-signaled regions this is the signaling id (DASH `Event@id`, HLS `DATERANGE
   * ID`), which is unique per manifest and is not an ad identifier.
   */
  readonly id: string;
  /** Whether the region is commercial. Bumpers, recaps and slates are `content`. */
  readonly kind: 'ad' | 'content';
  readonly insertion: InsertionMode;
  readonly cue: CuePosition;
  /** When true, the region leaves the schedule after it completes. */
  readonly playOnce: boolean;

  /** Stream time at which the region begins. `null` only for a `post` region on live. */
  startTime: number | null;
  /** Duration announced before the region resolves (HLS `PLANNED-DURATION`, SCTE-35 break duration). */
  plannedDuration: number | null;
  /** Actual duration once known. Equals the sum of slot durations when resolved. */
  duration: number | null;
  /** `startTime + duration` when both are known. */
  readonly endTime: number | null;
  /**
   * Where primary resumes relative to `startTime` after an `inserted` or `replaced` region. `null` means the default
   * for the insertion mode (`0` for `inserted`, `duration` for `replaced`). Ignored for `stitched`.
   */
  resumeOffset: number | null;
  /** Maximum seconds the region may present. When reached, the region ends with reason `playoutLimit`. */
  playoutLimit: number | null;
  restrictions: ReadonlySet<NavigationRestriction>;
  snap: InterstitialSnap;
  timelineOccupancy: TimelineOccupancy;
  timelineStyle: TimelineStyle;

  readonly state: InterstitialState;
  readonly resolution: ResolutionState;
  /** True once the region has completed at least once. Not reset on replay. */
  readonly played: boolean;

  /** Ordered slots. Empty until resolved. */
  readonly slots: ReadonlyArray<Slot>;
  readonly currentSlot: Slot | null;
  /** Seconds elapsed inside the region. `0` when not active. */
  readonly currentTime: number;
  /** `duration - currentTime`, or `null` when the duration is unknown. */
  readonly remainingTime: number | null;

  /** Pod-level tracking (`podStart`, `podEnd`). */
  tracking: TrackingEvent[];
  /** Adapter pass-through (SCTE-35 payload, vendor break id). */
  metadata: Record<string, unknown>;

  /**
   * Ends the region now and resumes primary. Throws if `restrictions` has `skip` or `state !== 'active'`. For
   * `stitched`, seeks the primary element to `endTime`.
   */
  skip(): void;
}

/**
 * One creative within an interstitial: the SVTA2053 `Slot` object plus runtime fields.
 *
 * @internal
 */
export interface Slot {
  /** Unique within the session. Generated by the host if the source has none. */
  readonly id: string;
  readonly interstitial: Interstitial;
  /** 0-based position in `interstitial.slots`. Pod position for UI is `index + 1` of `interstitial.slots.length`. */
  readonly index: number;

  /** Only `linear` is defined by SVTA2053 today. */
  type: 'linear';
  /** Seconds from the interstitial start. */
  start: number;
  duration: number;
  /** One or more scheme/value pairs. Required for `kind: 'ad'`. */
  identifiers: AdIdentifier[];
  /** Creative media. Empty for `stitched`; required for `inserted` and `replaced`. */
  media: MediaReference[];
  tracking: TrackingEvent[];
  verifications: Verification[];
  /** When and how the skip button appears. `null` means not skippable. */
  skipControl: SkipControl | null;
  clickThrough: string | null;
  title: string | null;

  readonly state: SlotState;
  /** Seconds elapsed in this slot. */
  readonly currentTime: number;
  /** `duration - currentTime`. */
  readonly remainingTime: number;
  /** True when `skipControl` is set, `currentTime >= skipControl.offset`, and the interstitial does not restrict `skip`. */
  readonly skippable: boolean;

  /** Adapter pass-through (VAST wrapper ids, ad system). */
  metadata: Record<string, unknown>;

  /** Ends this slot and advances to the next. Throws if `!skippable`. Fires `slotskip` and the `skip` tracking record. */
  skip(): void;
  /**
   * Reports a click-through activation. Fires `slotclick` and the `clickTracking` record. Does not navigate; the
   * integrator opens `clickThrough`.
   */
  click(): void;
}

/**
 * What an adapter supplies to create an interstitial. Runtime fields are session-owned, so they are absent here; every
 * field but `id` and `startTime` has a default.
 *
 * @internal
 */
export interface InterstitialInit {
  id: string;
  /** @default 'ad' */
  kind?: 'ad' | 'content' | undefined;
  /** @default 'stitched' */
  insertion?: InsertionMode | undefined;
  /** @default 'mid' */
  cue?: CuePosition | undefined;
  /** @default false */
  playOnce?: boolean | undefined;
  startTime: number | null;
  plannedDuration?: number | null | undefined;
  duration?: number | null | undefined;
  resumeOffset?: number | null | undefined;
  playoutLimit?: number | null | undefined;
  /** @default none */
  restrictions?: Iterable<NavigationRestriction> | undefined;
  snap?: InterstitialSnap | undefined;
  /** @default `'point'` for `inserted`, `'range'` otherwise */
  timelineOccupancy?: TimelineOccupancy | undefined;
  /** @default 'highlight' */
  timelineStyle?: TimelineStyle | undefined;
  tracking?: TrackingEvent[] | undefined;
  metadata?: Record<string, unknown> | undefined;
}

/** @internal */
export type InterstitialPatch = Partial<Omit<InterstitialInit, 'id' | 'kind' | 'insertion' | 'playOnce'>>;

/**
 * What an adapter supplies to create a slot. The SVTA2053 `Slot` fields; runtime fields are session-owned.
 *
 * @internal
 */
export interface SlotInit {
  /** Defaults to `<interstitial id>:<index>`. */
  id?: string | undefined;
  type?: 'linear' | undefined;
  start: number;
  duration: number;
  identifiers?: AdIdentifier[] | undefined;
  media?: MediaReference[] | undefined;
  tracking?: TrackingEvent[] | undefined;
  verifications?: Verification[] | undefined;
  skipControl?: SkipControl | null | undefined;
  clickThrough?: string | null | undefined;
  title?: string | null | undefined;
  metadata?: Record<string, unknown> | undefined;
}

