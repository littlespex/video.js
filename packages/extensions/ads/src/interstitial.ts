/**
 * The mutable record behind an {@link Interstitial}. Only the session reaches it, through {@link interstitialData}.
 *
 * @internal
 */
export interface InterstitialData {
  /** Arrival order, which orders regions whose start is unknown. */
  readonly order: number;
  startTime: number | null;
  plannedDuration: number | null;
  duration: number | null;
  resumeOffset: number | null;
  playoutLimit: number | null;
  restrictions: Set<NavigationRestriction>;
  snap: InterstitialSnap;
  timelineOccupancy: TimelineOccupancy;
  timelineStyle: TimelineStyle;
  tracking: TrackingEvent[];
  metadata: Record<string, unknown>;
  state: InterstitialState;
  resolution: ResolutionState;
  played: boolean;
  slots: SlotImpl[];
  currentSlot: SlotImpl | null;
  currentTime: number;
  /** Pod-level records fired during the current activation. */
  fired: Set<TrackingEvent>;
}

/**
 * The mutable record behind a {@link Slot}. Only the session reaches it, through {@link slotData}.
 *
 * @internal
 */
export interface SlotData {
  index: number;
  type: 'linear';
  start: number;
  duration: number;
  identifiers: AdIdentifier[];
  media: MediaReference[];
  tracking: TrackingEvent[];
  verifications: Verification[];
  skipControl: SkipControl | null;
  clickThrough: string | null;
  title: string | null;
  metadata: Record<string, unknown>;
  state: SlotState;
  currentTime: number;
  skippable: boolean;
  /** Slot-level records fired during the current activation. */
  fired: Set<TrackingEvent>;
  /** Quartile fractions already reported through `slotprogress` during the current activation. */
  progressFired: Set<number>;
}

/**
 * What the session does on behalf of the objects it hands out.
 *
 * @internal
 */
export interface InterstitialHooks {
  update(interstitial: InterstitialImpl, patch: InterstitialPatch): void;
  skipInterstitial(interstitial: InterstitialImpl): void;
  skipSlot(slot: SlotImpl): void;
  clickSlot(slot: SlotImpl): void;
}

const interstitialRecords = new WeakMap<Interstitial, InterstitialData>();
const slotRecords = new WeakMap<Slot, SlotData>();

/** @internal */
export function interstitialData(interstitial: Interstitial): InterstitialData {
  const data = interstitialRecords.get(interstitial);
  if (!data) throw new TypeError('Interstitial does not belong to this session');

  return data;
}

/** @internal */
export function slotData(slot: Slot): SlotData {
  const data = slotRecords.get(slot);
  if (!data) throw new TypeError('Slot does not belong to this session');

  return data;
}

/** @internal */
export class InterstitialImpl implements Interstitial {
  readonly id: string;
  readonly kind: 'ad' | 'content';
  readonly insertion: InsertionMode;
  readonly cue: CuePosition;
  readonly playOnce: boolean;

  readonly #data: InterstitialData;
  readonly #hooks: InterstitialHooks;

  constructor(init: InterstitialInit, order: number, hooks: InterstitialHooks) {
    this.id = init.id;
    this.kind = init.kind ?? 'ad';
    this.insertion = init.insertion ?? 'stitched';
    this.cue = init.cue ?? 'mid';
    this.playOnce = init.playOnce ?? false;
    this.#hooks = hooks;

    this.#data = {
      order,
      startTime: init.startTime,
      plannedDuration: init.plannedDuration ?? null,
      duration: init.duration ?? null,
      resumeOffset: init.resumeOffset ?? null,
      playoutLimit: init.playoutLimit ?? null,
      restrictions: new Set(init.restrictions ?? []),
      snap: init.snap ?? { out: false, in: false },
      timelineOccupancy: init.timelineOccupancy ?? (this.insertion === 'inserted' ? 'point' : 'range'),
      timelineStyle: init.timelineStyle ?? 'highlight',
      tracking: init.tracking ?? [],
      metadata: init.metadata ?? {},
      state: 'scheduled',
      resolution: 'unresolved',
      played: false,
      slots: [],
      currentSlot: null,
      currentTime: 0,
      fired: new Set(),
    };

    interstitialRecords.set(this, this.#data);
  }

  get startTime(): number | null {
    return this.#data.startTime;
  }

  set startTime(value: number | null) {
    this.#hooks.update(this, { startTime: value });
  }

  get plannedDuration(): number | null {
    return this.#data.plannedDuration;
  }

  set plannedDuration(value: number | null) {
    this.#hooks.update(this, { plannedDuration: value });
  }

  get duration(): number | null {
    return this.#data.duration;
  }

  set duration(value: number | null) {
    this.#hooks.update(this, { duration: value });
  }

  get endTime(): number | null {
    const { startTime, duration } = this.#data;

    return startTime !== null && duration !== null ? startTime + duration : null;
  }

  get resumeOffset(): number | null {
    return this.#data.resumeOffset;
  }

  set resumeOffset(value: number | null) {
    this.#hooks.update(this, { resumeOffset: value });
  }

  get playoutLimit(): number | null {
    return this.#data.playoutLimit;
  }

  set playoutLimit(value: number | null) {
    this.#hooks.update(this, { playoutLimit: value });
  }

  get restrictions(): ReadonlySet<NavigationRestriction> {
    return this.#data.restrictions;
  }

  set restrictions(value: Iterable<NavigationRestriction>) {
    this.#hooks.update(this, { restrictions: value });
  }

  get snap(): InterstitialSnap {
    return this.#data.snap;
  }

  set snap(value: InterstitialSnap) {
    this.#hooks.update(this, { snap: value });
  }

  get timelineOccupancy(): TimelineOccupancy {
    return this.#data.timelineOccupancy;
  }

  set timelineOccupancy(value: TimelineOccupancy) {
    this.#hooks.update(this, { timelineOccupancy: value });
  }

  get timelineStyle(): TimelineStyle {
    return this.#data.timelineStyle;
  }

  set timelineStyle(value: TimelineStyle) {
    this.#hooks.update(this, { timelineStyle: value });
  }

  get state(): InterstitialState {
    return this.#data.state;
  }

  get resolution(): ResolutionState {
    return this.#data.resolution;
  }

  get played(): boolean {
    return this.#data.played;
  }

  get slots(): ReadonlyArray<Slot> {
    return this.#data.slots;
  }

  get currentSlot(): Slot | null {
    return this.#data.currentSlot;
  }

  get currentTime(): number {
    return this.#data.currentTime;
  }

  get remainingTime(): number | null {
    const { duration, currentTime } = this.#data;

    return duration === null ? null : Math.max(0, duration - currentTime);
  }

  get tracking(): TrackingEvent[] {
    return this.#data.tracking;
  }

  set tracking(value: TrackingEvent[]) {
    this.#hooks.update(this, { tracking: value });
  }

  get metadata(): Record<string, unknown> {
    return this.#data.metadata;
  }

  set metadata(value: Record<string, unknown>) {
    this.#hooks.update(this, { metadata: value });
  }

  skip(): void {
    if (this.#data.state !== 'active') throw new Error(`Interstitial "${this.id}" is not active`);

    if (this.#data.restrictions.has('skip')) throw new Error(`Interstitial "${this.id}" restricts skipping`);

    this.#hooks.skipInterstitial(this);
  }
}

/** @internal */
export class SlotImpl implements Slot {
  readonly id: string;
  readonly interstitial: InterstitialImpl;

  readonly #data: SlotData;
  readonly #hooks: InterstitialHooks;

  constructor(interstitial: InterstitialImpl, index: number, init: SlotInit, hooks: InterstitialHooks) {
    this.id = init.id ?? `${interstitial.id}:${index}`;
    this.interstitial = interstitial;
    this.#hooks = hooks;

    this.#data = {
      index,
      type: init.type ?? 'linear',
      start: init.start,
      duration: init.duration,
      identifiers: init.identifiers ?? [],
      media: init.media ?? [],
      tracking: init.tracking ?? [],
      verifications: init.verifications ?? [],
      skipControl: init.skipControl ?? null,
      clickThrough: init.clickThrough ?? null,
      title: init.title ?? null,
      metadata: init.metadata ?? {},
      state: 'pending',
      currentTime: 0,
      skippable: false,
      fired: new Set(),
      progressFired: new Set(),
    };

    slotRecords.set(this, this.#data);
  }

  get index(): number {
    return this.#data.index;
  }

  get type(): 'linear' {
    return this.#data.type;
  }

  set type(value: 'linear') {
    this.#data.type = value;
  }

  get start(): number {
    return this.#data.start;
  }

  set start(value: number) {
    this.#data.start = value;
  }

  get duration(): number {
    return this.#data.duration;
  }

  set duration(value: number) {
    this.#data.duration = value;
  }

  get identifiers(): AdIdentifier[] {
    return this.#data.identifiers;
  }

  set identifiers(value: AdIdentifier[]) {
    this.#data.identifiers = value;
  }

  get media(): MediaReference[] {
    return this.#data.media;
  }

  set media(value: MediaReference[]) {
    this.#data.media = value;
  }

  get tracking(): TrackingEvent[] {
    return this.#data.tracking;
  }

  set tracking(value: TrackingEvent[]) {
    this.#data.tracking = value;
  }

  get verifications(): Verification[] {
    return this.#data.verifications;
  }

  set verifications(value: Verification[]) {
    this.#data.verifications = value;
  }

  get skipControl(): SkipControl | null {
    return this.#data.skipControl;
  }

  set skipControl(value: SkipControl | null) {
    this.#data.skipControl = value;
  }

  get clickThrough(): string | null {
    return this.#data.clickThrough;
  }

  set clickThrough(value: string | null) {
    this.#data.clickThrough = value;
  }

  get title(): string | null {
    return this.#data.title;
  }

  set title(value: string | null) {
    this.#data.title = value;
  }

  get state(): SlotState {
    return this.#data.state;
  }

  get currentTime(): number {
    return this.#data.currentTime;
  }

  get remainingTime(): number {
    return Math.max(0, this.#data.duration - this.#data.currentTime);
  }

  get skippable(): boolean {
    return this.#data.skippable;
  }

  get metadata(): Record<string, unknown> {
    return this.#data.metadata;
  }

  set metadata(value: Record<string, unknown>) {
    this.#data.metadata = value;
  }

  skip(): void {
    if (!this.#data.skippable) throw new Error(`Slot "${this.id}" is not skippable`);

    this.#hooks.skipSlot(this);
  }

  click(): void {
    this.#hooks.clickSlot(this);
  }
}
